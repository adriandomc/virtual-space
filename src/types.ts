export type Point = { x: number; z: number };
export type Selection = { kind: 'wall'; index: number } | { kind: 'floor' | 'ceiling' } | { kind: 'furniture' | 'opening' | 'light'; id: string };
export type EditingSettings = { snap: boolean; step: number; bounds: boolean };
export type FloorFinish = 'wood' | 'tile-grid' | 'tile-brick' | 'tile-checker' | 'marble' | 'concrete';
export type DoorStyle = 'right' | 'left' | 'frame';
export type Opening = {
  id: string;
  type: 'door' | 'window';
  doorStyle?: DoorStyle;
  open?: boolean;
  wall: number;
  offset: number;
  width: number;
  height: number;
  sill: number;
};
export type RoomLight = {
  id: string;
  name: string;
  x: number;
  y: number;
  z: number;
  lumens: number;
  temperature: number;
  enabled: boolean;
};
export type BedSize = 'single' | 'double' | 'queen' | 'king';
export type FurnitureMaterial = 'wood' | 'plastic' | 'metal';
export type FurnitureItem = {
  id: string;
  type: 'bed' | 'wardrobe' | 'vanity' | 'nightstand';
  bedSize?: BedSize;
  material?: FurnitureMaterial;
  color?: string;
  x: number;
  z: number;
  width: number;
  depth: number;
  height: number;
  rotation: number;
};
export type Room = {
  version: 1;
  setupStep?: 0 | 1 | 2;
  name: string;
  vertices: Point[];
  wallColors: string[];
  height: number;
  thickness: number;
  floorColor: string;
  ceilingColor: string;
  floorFinish: FloorFinish;
  renderQuality: 'standard' | 'realistic' | 'hyperrealistic';
  editing: EditingSettings;
  showFurniture: boolean;
  furniture: FurnitureItem[];
  openings: Opening[];
  lights: RoomLight[];
  sun: { enabled: boolean; hour: number; azimuth: number; intensity: number };
};
export type ViewMode = 'orbit' | 'walk' | 'plan';
